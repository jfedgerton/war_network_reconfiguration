# 95_study_table.R -- appendix longtable listing every pooled replication study (descriptive only: no estimates).
# Inputs : registry.csv (pooled headline rows, pool_status == "main") and study_table_labels.csv (hand-coded labels,
#          2026-11-12, from each study's rerun script header and the registry estimator/model fields).
# Output : results/appendix/tableA_sweep_studies.tex  (\input in appendix.tex)
# Run from code/04_replication_sweep/.
suppressPackageStartupMessages({ library(dplyr); library(readr); library(stringr) })

out_file <- if (dir.exists("../../results/appendix")) "../../results/appendix/tableA_sweep_studies.tex" else "tableA_sweep_studies.tex"

reg <- read_csv("registry.csv", col_types = cols(.default = "c"), na = character())
lab <- read_csv("study_table_labels.csv", col_types = cols(.default = "c"), na = character())

pool <- reg %>% filter(pool_status == "main")
stopifnot(nrow(pool) == 142, !anyDuplicated(pool$id))   # [2026-11-13] 140 -> 142 (inv34, inv8 added)
stopifnot(setequal(pool$id, lab$id), !anyDuplicated(lab$id))
stopifnot(all(pool$family %in% c("TIE", "DEMOCRACY", "CAPITALISM")))

d <- pool %>% left_join(lab, by = "id")
stopifnot(all(nzchar(d$key_var_label)), all(nzchar(d$outcome_label)), all(nzchar(d$unit)), all(nzchar(d$estimator_label)))
stopifnot(!any(str_detect(paste(d$key_var_label, d$outcome_label, d$unit, d$estimator_label, d$model_override), fixed("?"))))

# study label: short_cite without the journal tag some entries carry
d$study <- str_remove(d$short_cite, "\\s+(BJPS|AJPS|II|JCR|APSR|ISQ|RESTUD|Sci Adv|JOP|JPR|PSRM)$")
d$study <- str_replace_all(d$study, "&", "\\\\&")

# published model: hand override where the registry field is blank or verbose, else the registry text up to the first ( [ or ;
reg_model <- d$headline_model %>% str_remove("\\s*\\[.*$") %>% str_remove("\\s*\\(.*$") %>% str_remove(";.*$") %>%
  str_trim() %>% str_remove(",$") %>% str_replace_all("\\bcol\\s", "col.~")
d$model <- ifelse(nzchar(d$model_override), d$model_override, reg_model)
stopifnot(all(nzchar(d$model)))
stopifnot(all(nzchar(d$bib_key)), !anyDuplicated(d$bib_key))
# every key must exist in bibliography.bib or sweep_studies.bib (paths relative to the Overleaf project copy, if present)
bibs <- c("sweep_studies.bib", "bibliography.bib")
bibs <- bibs[file.exists(bibs)]
if (length(bibs) > 0) {
  bib_keys <- unlist(lapply(bibs, function(f) str_match(readLines(f, warn = FALSE), "^@\\w+\\{\\s*([^,\\s]+)")[, 2]))
  stopifnot(all(d$bib_key %in% bib_keys))
}

d$journal_tex <- ifelse(d$journal == "forthcoming", "PSRM", d$journal)
d$journal_tex <- str_replace(d$journal_tex, "^PSRM forthcoming$", "PSRM")
d$fam_order <- match(d$family, c("TIE", "DEMOCRACY", "CAPITALISM"))
d <- d %>% arrange(fam_order, study)

fam_head <- c(TIE = "Relational ties", DEMOCRACY = "Democratic peace", CAPITALISM = "Capitalist peace")
lines <- c(
  "% Generated by code/04_replication_sweep/95_study_table.R -- do not edit by hand.",
  "\\begingroup",
  "\\singlespacing",
  "\\renewcommand{\\arraystretch}{1}",
  "\\scriptsize",
  "\\setlength{\\tabcolsep}{1.5pt}",
  "\\setlength{\\LTcapwidth}{\\textwidth}",
  "\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{3.1cm}>{\\raggedright\\arraybackslash}p{3.2cm}>{\\raggedright\\arraybackslash}p{2.7cm}>{\\raggedright\\arraybackslash}p{2.2cm}>{\\raggedright\\arraybackslash}p{2.4cm}>{\\raggedright\\arraybackslash}p{2.4cm}@{}}",
  "\\caption{Studies pooled in the replication sweep.}\\label{tab:sweep_studies}\\\\",
  "\\toprule",
  "Study & Key variable replicated & Outcome & Unit & Estimator & Published model \\\\",
  "\\midrule",
  "\\endfirsthead",
  "\\multicolumn{6}{@{}l}{\\textit{Table \\ref{tab:sweep_studies} continued}} \\\\",
  "\\toprule",
  "Study & Key variable replicated & Outcome & Unit & Estimator & Published model \\\\",
  "\\midrule",
  "\\endhead",
  "\\midrule \\multicolumn{6}{r@{}}{\\textit{Continued on next page}} \\\\",
  "\\endfoot",
  "\\bottomrule",
  "\\multicolumn{6}{@{}p{\\linewidth}@{}}{\\textit{Note:} UDY = undirected dyad-years; DDY = directed dyad-years; PRD = politically relevant dyad-years. Published model is the model that carries the headline claim. ($t+1$) marks outcomes measured one year after the predictors.} \\\\",
  "\\endlastfoot"
)
for (f in c("TIE", "DEMOCRACY", "CAPITALISM")) {
  s <- d %>% filter(family == f)
  lines <- c(lines, sprintf("\\multicolumn{6}{@{}l}{\\textit{%s (%d studies)}} \\\\", fam_head[[f]], nrow(s)))
  lines <- c(lines, sprintf("\\cite{%s} & %s & %s & %s & %s & %s \\\\",
                            s$bib_key, s$key_var_label, s$outcome_label, s$unit, s$estimator_label, s$model))
  if (f != "CAPITALISM") lines <- c(lines, "\\addlinespace")
}
lines <- c(lines, "\\end{longtable}", "\\endgroup")

n_rows <- sum(str_detect(lines, " \\\\\\\\$") & !str_detect(lines, "multicolumn|^Study|toprule|midrule|caption"))
stopifnot(n_rows == 142)   # [2026-11-13] was 140
writeLines(lines, out_file)
cat("wrote", out_file, "rows", n_rows, "| by family:", paste(names(table(d$family)), table(d$family), collapse = " "), "\n")
