# Same quantities as the old figure: observed coefficient, the permutation null and the two-sided p-value
# mean(|null| >= |observed|), reported as p < 1/draws when no draw reaches the observed value.
# Run from the repository root:  Rscript code/03_figures/08_table_permutation.R
###############################################################################
suppressPackageStartupMessages({ library(dplyr); library(readr) })
ROOT <- Sys.getenv("PIPE_ROOT", unset = here::here())

perm <- read_csv(file.path(ROOT, "data/processed/robustness_placebo_permutation.csv"), show_col_types = FALSE)
rev  <- read_csv(file.path(ROOT, "data/processed/robustness_placebo_reverse_timing.csv"), show_col_types = FALSE)

# focal terms, as in the old figure (04_robustness_placebos.R, PLOT A)
SYS_TERM <- "log_fatal_mid_count_lag1"
ST_TERM  <- "log_fatal_onset_lag1"

null_sys <- perm |> filter(level == "system", term == SYS_TERM) |> pull(estimate)
null_st  <- perm |> filter(level == "state",  term == ST_TERM)  |> pull(estimate)
obs_sys  <- rev  |> filter(level == "system", term == SYS_TERM, horizon == 0) |> pull(estimate)
obs_st   <- rev  |> filter(level == "state",  term == ST_TERM,  horizon == 0) |> pull(estimate)

# fail loudly if the inputs are not what the table describes
stopifnot(length(null_sys) == 1000, length(null_st) == 1000,
          !anyNA(null_sys), !anyNA(null_st),
          length(obs_sys) == 1, length(obs_st) == 1)

f4 <- function(x) sprintf("%.4f", ifelse(abs(x) < 5e-5, 0, x))   # no "-0.0000"
p_txt <- function(null, obs) {
  p <- mean(abs(null) >= abs(obs))
  if (p == 0) sprintf("$<$%.3f", 1 / length(null)) else sprintf("%.3f", p)
}
# [2026-11-14] stars on the observed coefficient from the permutation p (PI: every coefficient table carries stars)
pstar <- function(null, obs) { p <- max(mean(abs(null) >= abs(obs)), 1 / length(null))   # p = 0 is bounded at 1 / draws
  ifelse(p < 0.001 | mean(abs(null) >= abs(obs)) == 0, "$^{***}$", ifelse(p < 0.01, "$^{**}$", ifelse(p < 0.05, "$^{*}$", ""))) }
row_tex <- function(lab, null, obs) {
  paste(c(lab, paste0(f4(obs), pstar(null, obs)), f4(mean(null)), f4(sd(null)),
          f4(quantile(null, 0.95, names = FALSE)), f4(quantile(null, 0.99, names = FALSE)), f4(max(abs(null))),
          sprintf("%d of %s", sum(abs(null) >= abs(obs)), format(length(null), big.mark = ",")),
          p_txt(null, obs)), collapse = " & ")
}

lines <- c(
  "% Generated by code/03_figures/08_table_permutation.R -- do not edit by hand.",
  "\\begin{table}[!htbp]",
  "\\centering",
  "\\footnotesize",
  "\\caption{Permutation tests. The conflict coefficient compared with its distribution when conflict is randomly reassigned across years (1,000 draws).}",
  "\\label{tab:permutation_values}",
  "\\setlength{\\tabcolsep}{4pt}",
  "\\begin{tabular}{@{}lrrrrrrrr@{}}",
  "\\toprule",
  " & & \\multicolumn{5}{c}{Permutation distribution} & Draws at or beyond & Permutation \\\\",
  "\\cmidrule(lr){3-7}",
  "Level & Observed & Mean & SD & 95th pct. & 99th pct. & Max. $|$draw$|$ & $|$observed$|$ & $p$ \\\\",
  "\\midrule",
  paste0(row_tex("System", null_sys, obs_sys), " \\\\"),
  paste0(row_tex("State",  null_st,  obs_st),  " \\\\"),
  "\\bottomrule",
  "\\end{tabular}",
  "\\par\\smallskip",
  "\\begin{minipage}{\\linewidth}\\scriptsize \\textit{Note:} The system level shuffles lagged fatal MIDs across years; the state level shuffles fatal MID onsets across years within state. The two-sided $p$ is the share of draws with absolute value at least the observed. Stars use the permutation $p$; $^{*}p < 0.05$, $^{**}p < 0.01$, $^{***}p < 0.001$.\\end{minipage}",
  "\\end{table}")
out <- file.path(ROOT, "results/appendix/tableA_permutation.tex")
dir.create(dirname(out), recursive = TRUE, showWarnings = FALSE)
writeLines(lines, out)
cat("wrote", out, "\n"); cat(lines, sep = "\n")
