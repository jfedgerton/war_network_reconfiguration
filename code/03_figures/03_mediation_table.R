###############################################################################
# 03_figures/03_mediation_table.R
#
# LaTeX table for the mediation battery (appendix companion to main-text
# Figure 7).
#
# STANDALONE BY DESIGN. It reads the CSV that 05_robustness_alt_mechanisms.R
# writes rather than living inside 05, so it can be re-run to restyle the table
# without paying for 1,000 bootstrap replications again.
#
# Replaces figs/tableA_mediation_altmech.tex, which was generated in June and
# is stale.
#
# THE LOGIC OF THE TABLE
#   Each row decomposes the total association between conflict (X) and network
#   reconfiguration (Y) into a DIRECT component (c') and an INDIRECT component
#   (a x b) running through a candidate mediator M.
#
#     c        total    X -> Y
#     a        X -> M
#     b        M -> Y | X
#     a*b      indirect (the mediated part)
#     c'       direct   X -> Y | M
#     % Med.   a*b / c
#
#   RIVAL MECHANISMS (power redistribution, regime change, territorial change,
#   system composition) should show an indirect effect whose 95% bootstrap CI
#   COVERS ZERO. That is what rules them out: conflict does not reshape networks
#   BY changing power / regimes / territory.
#
#   CONSISTENT CHANNELS (e.g. battle deaths) are NOT rival mechanisms -- war
#   severity is part of the conflict mechanism, not an alternative to it. They
#   are expected to mediate. They are reported in a separate panel so a reader
#   does not mistake a non-null there for a failed placebo.
#
# Input : data/processed/robustness_altmech_mediation.csv   (from 05)
# Output: results/appendix/tableA_mediation_altmech.tex
###############################################################################

library(tidyverse)

OUTPUT_DIR <- here::here("data", "processed")
TEX_DIR    <- here::here("results", "appendix")
dir.create(TEX_DIR, recursive = TRUE, showWarnings = FALSE)

in_csv <- file.path(OUTPUT_DIR, "robustness_altmech_mediation.csv")
if (!file.exists(in_csv)) {
  stop("robustness_altmech_mediation.csv not found. Run ",
       "02_analysis/05_robustness_alt_mechanisms.R first.")
}

med <- read_csv(in_csv, show_col_types = FALSE)
cat(sprintf("Loaded %d mediation rows.\n", nrow(med)))

# --------------------------------------------------------------------------- #
# Formatting helpers
# --------------------------------------------------------------------------- #
stars <- function(p) {
  dplyr::case_when(is.na(p) ~ "", p < 0.001 ~ "$^{***}$", p < 0.01 ~ "$^{**}$",
                   p < 0.05 ~ "$^{*}$", p < 0.10 ~ "$^{\\dagger}$", TRUE ~ "")
}
num <- function(x, d = 4) ifelse(is.na(x), "---", formatC(x, format = "f", digits = d))

# `indirect_ci_low/high` are the 1,000-rep cluster-bootstrap bounds. Whether the
# interval COVERS ZERO is the entire test -- flag it explicitly so a reader does
# not have to compare two numbers in their head.
med <- med |>
  mutate(
    covers_zero = indirect_ci_low <= 0 & indirect_ci_high >= 0,
    pct_med_disp = 100 * pct_mediated,          # stored as a proportion
    ci_disp = sprintf("[%s, %s]", num(indirect_ci_low, 5), num(indirect_ci_high, 5)),
    verdict = ifelse(covers_zero, "CI covers 0", "CI excludes 0")
  )

fmt_panel <- function(dat) {
  dat |>
    transmute(
      Mediator = mediator_label,
      `IV`     = iv_label,
      `Total ($c$)`         = paste0(num(c_total), stars(c_total_p)),
      `Indirect ($a\\times b$)` = num(indirect_ab, 5),
      `95\\% CI`            = ci_disp,
      `\\% Med.`            = num(pct_med_disp, 1),
      `Direct ($c'$)`       = paste0(num(c_prime), stars(c_prime_p)),
      Verdict               = verdict
    )
}

# --------------------------------------------------------------------------- #
# Build the panels
# --------------------------------------------------------------------------- #
is_rival <- grepl("Rival", med$mediator_type)

panels <- list(
  "Panel A: State level, rival mechanisms (indirect effect should be null)" =
    med |> filter(level == "state",  is_rival)  |> fmt_panel(),
  "Panel B: System level, rival mechanisms (indirect effect should be null)" =
    med |> filter(level == "system", is_rival)  |> fmt_panel(),
  "Panel C: Consistent channels (not rival mechanisms; mediation expected)" =
    med |> filter(!is_rival) |> fmt_panel()
)
panels <- panels[sapply(panels, nrow) > 0]

# --------------------------------------------------------------------------- #
# Emit LaTeX
# --------------------------------------------------------------------------- #
ncol_tab <- 8
lines <- c(
  "% Auto-generated by code/03_figures/03_mediation_table.R -- do not hand-edit.",
  "\\begin{table}[htbp]",
  "\\centering",
  "\\footnotesize",
  "\\caption{Mediation analyses. Each row decomposes the association between",
  "conflict and network reconfiguration into a direct component ($c'$) and an",
  "indirect component ($a\\times b$) running through the listed mediator.",
  "Confidence intervals are 1,000-replication cluster bootstraps. A rival",
  "mechanism is ruled out when its indirect effect's interval covers zero.}",
  "\\label{tab:mediation_altmech}",
  paste0("\\begin{tabular}{ll", strrep("r", 4), "l l}"),
  "\\toprule",
  "Mediator & IV & Total ($c$) & Indirect ($a\\times b$) & 95\\% CI & \\% Med. & Direct ($c'$) & Verdict \\\\",
  "\\midrule"
)

for (pn in names(panels)) {
  lines <- c(lines,
             sprintf("\\multicolumn{%d}{l}{\\textit{%s}} \\\\", ncol_tab, pn),
             "\\addlinespace[2pt]")
  p <- panels[[pn]]
  for (i in seq_len(nrow(p))) {
    lines <- c(lines, paste(paste(as.character(unlist(p[i, ])), collapse = " & "), "\\\\"))
  }
  lines <- c(lines, "\\addlinespace[4pt]")
}

lines <- c(lines,
  "\\bottomrule",
  "\\end{tabular}",
  paste0("\\begin{minipage}{\\textwidth}\\vspace{2pt}\\scriptsize ",
         "$^{\\dagger}p<0.10$; $^{*}p<0.05$; $^{**}p<0.01$; $^{***}p<0.001$. ",
         "Indirect effects and their intervals come from a cluster bootstrap ",
         "(resampling states, fresh cluster ids). Percent mediated is ",
         "$a\\times b / c$ and is not meaningful when $c$ is near zero. ",
         "Consistent channels are reported separately because they are part of ",
         "the conflict mechanism rather than alternatives to it; a non-null ",
         "indirect effect there is expected and is not a failed placebo.",
         "\\end{minipage}"),
  "\\end{table}"
)

out_tex <- file.path(TEX_DIR, "tableA_mediation_altmech.tex")
writeLines(lines, out_tex)
cat(sprintf("\nWrote %s  (%d rows across %d panels)\n",
            out_tex, sum(sapply(panels, nrow)), length(panels)))

# --------------------------------------------------------------------------- #
# Console summary -- what the table says
# --------------------------------------------------------------------------- #
cat("\n=== RIVAL MECHANISMS: is the indirect effect null? ===\n")
print(med |> filter(is_rival) |>
        select(level, mediator_label, iv_label, indirect_ab,
               indirect_ci_low, indirect_ci_high, verdict),
      n = Inf)

n_rival   <- sum(is_rival)
n_covered <- sum(is_rival & med$covers_zero)
cat(sprintf("\n  %d of %d rival-mechanism indirect effects have a CI covering zero.\n",
            n_covered, n_rival))
if (n_covered < n_rival) {
  cat("  The ones that do NOT are listed below -- these need a sentence in the text.\n")
  print(med |> filter(is_rival, !covers_zero) |>
          select(level, mediator_label, iv_label, indirect_ab, pct_med_disp), n = Inf)
}

cat("\n=== CONSISTENT CHANNELS (expected to mediate) ===\n")
cc <- med |> filter(!is_rival)
if (nrow(cc)) {
  print(cc |> select(level, mediator_label, iv_label, indirect_ab, verdict), n = Inf)
  cat("\n  NOTE: battle deaths is a CONSISTENT channel, not a rival mechanism --\n")
  cat("  war severity is part of the conflict mechanism. If you would rather not\n")
  cat("  report it at all, drop it in 05 and re-run; this script will follow.\n")
} else {
  cat("  (none in the CSV)\n")
}
