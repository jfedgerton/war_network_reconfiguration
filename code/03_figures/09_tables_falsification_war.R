suppressPackageStartupMessages({ library(dplyr); library(readr) })
ROOT <- Sys.getenv("PIPE_ROOT", unset = here::here())
PROC <- file.path(ROOT, "data/processed"); APP <- file.path(ROOT, "results/appendix")
dir.create(APP, recursive = TRUE, showWarnings = FALSE)
neg <- function(x, d) ifelse(x < 0, paste0("$-$", sprintf(paste0("%.", d, "f"), abs(x))), sprintf(paste0("%.", d, "f"), x))

# ---- (1) falsification: attenuation (%) with past history, future conflict, and the permutation null ----
fals <- read_csv(file.path(PROC, "contamination_falsification.csv"), show_col_types = FALSE)
perm <- read_csv(file.path(PROC, "contamination_permutation_summary.csv"), show_col_types = FALSE)
LAYERS <- c("Alliance", "IGO", "Multiplex")
COND <- c(dyad_past = "Dyadic conflict, past t-2..t-6", mono_past = "Monadic conflict, past t-2..t-6",
          dyad_fut = "DIAGNOSTIC: dyadic conflict, future t+2..t+6", mono_fut = "DIAGNOSTIC: monadic conflict, future t+2..t+6")
stopifnot(nrow(fals) == 15, setequal(fals$layer, LAYERS), all(COND %in% fals$condition), !anyNA(fals$attenuation_pct),
          nrow(perm) == 6, setequal(perm$layer, LAYERS), setequal(perm$measure, c("Dyadic", "Monadic")))
att <- function(l, k) { v <- fals$attenuation_pct[fals$layer == l & fals$condition == COND[[k]]]; stopifnot(length(v) == 1); v }
pci <- function(l, m) { r <- perm[perm$layer == l & perm$measure == m, ]; stopifnot(nrow(r) == 1)
  # the observed value in the permutation file must be the past-history attenuation above
  stopifnot(abs(r$obs_atten - att(l, if (m == "Dyadic") "dyad_past" else "mono_past")) < 1e-8)
  sprintf("[%s, %s]", neg(r$null_q025, 3), neg(r$null_q975, 3)) }
rows1 <- sapply(LAYERS, function(l) paste(c(l,
  neg(att(l, "dyad_past"), 1), neg(att(l, "dyad_fut"), 1), pci(l, "Dyadic"),
  neg(att(l, "mono_past"), 1), neg(att(l, "mono_fut"), 1), pci(l, "Monadic")), collapse = " & "))
t1 <- c("% Generated by code/03_figures/09_tables_falsification_war.R -- do not edit by hand.",
  "\\begin{table}[!htbp]", "\\centering", "\\footnotesize",
  "\\caption{Falsification tests. Cells are the attenuation (\\%) of the tie coefficient.}",
  "\\label{tab:contam_falsification}", "\\setlength{\\tabcolsep}{4pt}",
  "\\begin{tabular}{@{}lcccccc@{}}", "\\toprule",
  " & \\multicolumn{3}{c}{Dyadic conflict (i--j)} & \\multicolumn{3}{c}{Monadic conflict (third-party)} \\\\",
  "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
  "Tie & Past & Future & Permuted past, & Past & Future & Permuted past, \\\\",
  " & ($t-2\\ldots t-6$) & ($t+2\\ldots t+6$) & 95\\% interval & ($t-2\\ldots t-6$) & ($t+2\\ldots t+6$) & 95\\% interval \\\\",
  "\\midrule", paste0(rows1, " \\\\"), "\\bottomrule", "\\end{tabular}", "\\par\\smallskip",
  "\\begin{minipage}{\\linewidth}\\scriptsize \\textit{Note:} Attenuation is the percentage change in the tie coefficient toward zero when the conflict term is added to the step 2 regression; negative values indicate movement away from zero. The permuted columns give the 2.5th and 97.5th percentiles of the attenuation across 200 draws in which past conflict history is randomly reassigned across dyads within year. No permuted draw reaches the observed past value.\\end{minipage}",
  "\\end{table}")
stopifnot(all(perm$p_perm == 0))   # the note's last sentence
writeLines(t1, file.path(APP, "tableA_contam_falsification.tex")); cat("wrote tableA_contam_falsification.tex\n"); cat(t1, sep = "\n")

# ---- (2) fatal-MID samples, log(1 + fatal MIDs) at t-1 ----
ws <- read_csv(file.path(PROC, "robustness_war_samples.csv"), show_col_types = FALSE)
stopifnot(all(c("level", "sample", "iv", "estimate", "se", "n_obs", "nw_se") %in% names(ws)))
pick <- function(lev, iv_col, smp) { r <- ws[ws$level == lev & ws$iv == iv_col & ws$sample == smp, ]; stopifnot(nrow(r) == 1, is.finite(r$estimate), is.finite(r$se)); r }
SYS <- c("Full sample" = "(1) Full sample", "Years with at least 3 fatal MIDs" = "(3) Fatal MIDs >= 3",
         "Years with at least 5 fatal MIDs" = "(3) Fatal MIDs >= 5", "Years with at least 10 fatal MIDs" = "(3) Fatal MIDs >= 10")
ST  <- c("Fatality level 1 or higher (any deaths; main)" = "(1) Full sample", "Fatality level 2 or higher (26+ deaths)" = "(4) Fatality >= 2",
         "Fatality level 3 or higher (101+ deaths)" = "(4) Fatality >= 3", "Fatality level 4 or higher (251+ deaths)" = "(4) Fatality >= 4")
f4 <- function(x) sprintf("%.4f", x)
# [2026-11-14] stars (PI request), same cutoffs as the main-text tables; system stars use the Newey--West SE (main-text inference), state the clustered SE
stars <- function(b, se) { p <- 2 * pnorm(-abs(b / se)); ifelse(p < 0.001, "$^{***}$", ifelse(p < 0.01, "$^{**}$", ifelse(p < 0.05, "$^{*}$", ""))) }
row_sys <- sapply(names(SYS), function(nm) { r <- pick("system", "log_fatal_mid_count_lag1", SYS[[nm]]); stopifnot(is.finite(r$nw_se))
  paste(nm, paste0(f4(r$estimate), stars(r$estimate, r$nw_se)), f4(r$se), f4(r$nw_se), format(r$n_obs, big.mark = ","), sep = " & ") })
row_st  <- sapply(names(ST), function(nm) { r <- pick("state", "log_fatal_onset_lag1", ST[[nm]])
  paste(nm, paste0(f4(r$estimate), stars(r$estimate, r$se)), f4(r$se), "--", format(r$n_obs, big.mark = ","), sep = " & ") })
# both levels significant at .05 in every sample (the appendix text says so), with either system SE
zs <- sapply(SYS, function(s) { r <- pick("system", "log_fatal_mid_count_lag1", s); min(r$estimate / r$se, r$estimate / r$nw_se) })
zt <- sapply(ST,  function(s) { r <- pick("state", "log_fatal_onset_lag1", s); r$estimate / r$se })
cat("min z: system", round(min(zs), 2), " state", round(min(zt), 2), "\n")
t2 <- c("% Generated by code/03_figures/09_tables_falsification_war.R -- do not edit by hand.",
  "\\begin{table}[!htbp]", "\\centering", "\\footnotesize",
  "\\caption{Conflict and network reconfiguration in fatal-MID samples, with $\\log(1+x)$ fatal MIDs at $t-1$.}",
  "\\label{tab:war_samples}", "\\setlength{\\tabcolsep}{5pt}",
  "\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
  "Sample & Coefficient & Standard error & Newey--West SE & $N$ \\\\", "\\midrule",
  "\\multicolumn{5}{@{}l}{\\textit{Panel A. System level (JS divergence)}} \\\\", paste0(row_sys, " \\\\"), "\\addlinespace",
  "\\multicolumn{5}{@{}l}{\\textit{Panel B. State level (churn)}} \\\\", paste0(row_st, " \\\\"),
  "\\bottomrule", "\\end{tabular}", "\\par\\smallskip",
  "\\begin{minipage}{\\linewidth}\\scriptsize \\textit{Note:} Panel A keeps years with at least 3, 5, or 10 fatal MIDs; the Newey--West SE (lag 5) matches the main text. Panel B raises the COW fatality level that defines a fatal MID; SEs clustered by state and year. Stars use the Newey--West SE (Panel A) and the clustered SE (Panel B); $^{*}p < 0.05$, $^{**}p < 0.01$, $^{***}p < 0.001$.\\end{minipage}",
  "\\end{table}")
writeLines(t2, file.path(APP, "tableA_war_samples.tex")); cat("wrote tableA_war_samples.tex\n"); cat(t2, sep = "\n")
