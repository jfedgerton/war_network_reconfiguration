###############################################################################
# 07_table_contam_spec.R   [2026-11-12]
# Appendix table replacing fig_app_compact_contam_spec.png (alternative samples and gapped history window).
# Input : data/processed/contamination_specification.csv (21_contamination_specification.R)
# Output: results/appendix/tableA_contam_spec.tex  (upload to Overleaf tables_20261013/)
# Cells are attenuation (%) of the tie coefficient when the conflict-history term is added; negative = away from zero.
# Run from the repository root:  Rscript code/03_figures/07_table_contam_spec.R
###############################################################################
suppressPackageStartupMessages({ library(dplyr); library(readr); library(tidyr) })
ROOT <- Sys.getenv("PIPE_ROOT", unset = here::here())
spec <- read_csv(file.path(ROOT, "data/processed/contamination_specification.csv"), show_col_types = FALSE)
stopifnot(nrow(spec) == 24, !anyNA(spec$attenuation_pct),
          setequal(spec$layer, c("Alliance", "IGO", "Multiplex")), setequal(spec$process, c("Dyadic", "Monadic")),
          setequal(spec$window, c("main", "gap")), setequal(spec$sample_name, c("At-risk (MAIN)", "All dyads")))

wide <- spec |>
  mutate(col = paste(process, layer, sep = "_")) |>
  select(sample_name, window, col, attenuation_pct) |>
  pivot_wider(names_from = col, values_from = attenuation_pct)
n_by <- spec |> group_by(sample_name) |> summarise(n = unique(n_used), .groups = "drop")
stopifnot(nrow(n_by) == 2)                     # one N per sample (same N across layers, processes and windows)
wide <- wide |>
  left_join(n_by, by = "sample_name") |>
  mutate(s_ord = match(sample_name, c("At-risk (MAIN)", "All dyads")), w_ord = match(window, c("main", "gap"))) |>
  arrange(s_ord, w_ord)
stopifnot(nrow(wide) == 4)

COLS <- c("Dyadic_Alliance", "Dyadic_IGO", "Dyadic_Multiplex", "Monadic_Alliance", "Monadic_IGO", "Monadic_Multiplex")
f1 <- function(x) sprintf("%.1f", x)
row_tex <- function(i) {
  r <- wide[i, ]
  samp <- if (r$w_ord == 1) ifelse(r$sample_name == "At-risk (MAIN)", "At-risk (main)", "All dyads") else ""
  win  <- ifelse(r$window == "main", "$t-2$ to $t-6$", "$t-3$ to $t-7$")
  nn   <- if (r$w_ord == 1) format(r$n, big.mark = ",") else ""
  paste(c(samp, win, f1(unlist(r[COLS])), nn), collapse = " & ")
}
lines <- c(
  "% Generated by code/03_figures/07_table_contam_spec.R -- do not edit by hand.",
  "\\begin{table}[!htbp]",
  "\\centering",
  "\\footnotesize",
  "\\caption{Contamination ladder under alternative samples and a gapped history window. Cells are attenuation (\\%).}",
  "\\label{fig:contamination_sample_window}",
  "\\label{fig:contam_no_controls}",
  "\\setlength{\\tabcolsep}{4pt}",
  "\\begin{tabular}{@{}llrrrrrrr@{}}",
  "\\toprule",
  " & & \\multicolumn{3}{c}{Dyadic history (i--j)} & \\multicolumn{3}{c}{Monadic history (third-party)} & \\\\",
  "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
  "Sample & History window & Alliance & IGO & Multiplex & Alliance & IGO & Multiplex & $N$ \\\\",
  "\\midrule",
  paste0(row_tex(1), " \\\\"), paste0(row_tex(2), " \\\\"), "\\addlinespace",
  paste0(row_tex(3), " \\\\"), paste0(row_tex(4), " \\\\"),
  "\\bottomrule",
  "\\end{tabular}",
  "\\par\\smallskip",
  "\\begin{minipage}{\\linewidth}\\scriptsize \\textit{Note:} Attenuation as in Table \\ref{tab:contam_falsification}, with the conflict-history term$^{a}$. The at-risk sample drops dyad-years in an ongoing MID unless a new MID begins. $N$ is dyad-years.\\\\ $^{a}$ $\\log(1+x)$ of the MID onset count over the window, standardized.\\end{minipage}",
  "\\end{table}")
out <- file.path(ROOT, "results/appendix/tableA_contam_spec.tex")
dir.create(dirname(out), recursive = TRUE, showWarnings = FALSE)
writeLines(lines, out)
cat("wrote", out, "\n"); cat(lines, sep = "\n")
